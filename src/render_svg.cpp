#include <cmath>
#include <cstdio>

namespace protocol {

namespace {

std::string fmt(double v) {
    char buf[32];
    std::snprintf(buf, sizeof(buf), "%.2f", v);
    std::string s = buf;
    while (s.size() > 1 && s.back() == '0') s.pop_back();
    if (!s.empty() && s.back() == '.') s.pop_back();
    if (s == "-0") s = "0";
    return s;
}

std::string xml_escape(char c) {
    switch (c) {
        case '&': return "&amp;";
        case '<': return "&lt;";
        case '>': return "&gt;";
        case '"': return "&quot;";
        case '\'': return "&apos;";
        default: return std::string(1, c);
    }
}

Color fg_for(const Cell& cell, const Theme& theme, bool& visible) {
    visible = true;
    switch (cell.role) {
        case Role::Border: return theme.border;
        case Role::NumTen:
        case Role::NumUnit: return theme.numbers;
        case Role::FieldText: return theme.text;
        default: visible = false; return theme.text;
    }
}

} // namespace

std::string render_svg(const std::vector<Grid>& grids, const Theme& theme, const SvgOptions& opts) {
    const double cell_w = opts.font_size * 0.6;
    const double cell_h = opts.font_size * 1.25;
    const double pad_x = cell_w;
    const double pad_y = cell_h * 0.6;
    const double gap = cell_h; // vertical gap between stacked diagrams

    std::size_t max_cols = 0;
    std::size_t total_rows = 0;
    for (const Grid& g : grids) {
        max_cols = std::max(max_cols, g.width());
        total_rows += g.height();
    }
    if (!grids.empty()) total_rows += grids.size() - 1; // gaps, in cell units

    const double width = max_cols * cell_w + 2 * pad_x;
    const double height = total_rows * cell_h + 2 * pad_y;

    std::string svg;
    svg += "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"" + fmt(width) + "\" height=\"" +
           fmt(height) + "\" viewBox=\"0 0 " + fmt(width) + " " + fmt(height) + "\">\n";
    svg += "<title>Protocol header diagram - generated by protocol (C++ edition)</title>\n";
    if (!opts.transparent) {
        svg += "<rect x=\"0\" y=\"0\" width=\"" + fmt(width) + "\" height=\"" + fmt(height) +
               "\" fill=\"" + theme.background.to_hex() + "\"/>\n";
    }
    svg += "<g font-family=\"ui-monospace,SFMono-Regular,Menlo,Consolas,'DejaVu Sans Mono',monospace\""
           " font-size=\"" + fmt(opts.font_size) + "\" text-anchor=\"middle\" xml:space=\"preserve\">\n";

    double y_off = pad_y;
    for (const Grid& grid : grids) {
        for (std::size_t r = 0; r < grid.rows.size(); ++r) {
            const auto& row = grid.rows[r];
            // 1. Field background rectangles (merge contiguous cells of the
            //    same field).
            std::size_t col = 0;
            while (col < row.size()) {
                const Cell& c = row[col];
                bool is_field = (c.role == Role::FieldBg || c.role == Role::FieldText);
                if (!is_field) { ++col; continue; }
                std::size_t start = col;
                int field = c.field;
                while (col < row.size() &&
                       (row[col].role == Role::FieldBg || row[col].role == Role::FieldText) &&
                       row[col].field == field)
                    ++col;
                Color fill = theme.field_fill(field);
                svg += "<rect x=\"" + fmt(pad_x + start * cell_w) + "\" y=\"" + fmt(y_off) +
                       "\" width=\"" + fmt((col - start) * cell_w) + "\" height=\"" + fmt(cell_h) +
                       "\" fill=\"" + fill.to_hex() + "\"/>\n";
            }
            // 2. Border characters '+', '-' and '|' are drawn as continuous
            //    line primitives so boxes are perfectly closed (font glyphs
            //    would leave gaps between character rows).
            const double lw = opts.font_size * 0.085; // line width
            const std::string border_hex = theme.border.to_hex();
            // 2a. Horizontal segments, merged into runs.
            col = 0;
            while (col < row.size()) {
                if (!border_segments(grid.rows, r, col).hline) { ++col; continue; }
                std::size_t start = col;
                while (col < row.size() && border_segments(grid.rows, r, col).hline) ++col;
                svg += "<rect x=\"" + fmt(pad_x + start * cell_w) + "\" y=\"" +
                       fmt(y_off + cell_h / 2 - lw / 2) + "\" width=\"" +
                       fmt((col - start) * cell_w) + "\" height=\"" + fmt(lw) + "\" fill=\"" +
                       border_hex + "\"/>\n";
            }
            // 2b. Vertical segments.
            for (std::size_t ccol = 0; ccol < row.size(); ++ccol) {
                BorderSeg seg = border_segments(grid.rows, r, ccol);
                if (!seg.vline_up && !seg.vline_down) continue;
                double x = pad_x + ccol * cell_w + cell_w / 2 - lw / 2;
                double y0 = seg.vline_up ? y_off : y_off + cell_h / 2;
                double y1 = seg.vline_down ? y_off + cell_h : y_off + cell_h / 2;
                svg += "<rect x=\"" + fmt(x) + "\" y=\"" + fmt(y0) + "\" width=\"" + fmt(lw) +
                       "\" height=\"" + fmt(y1 - y0) + "\" fill=\"" + border_hex + "\"/>\n";
            }
            // 3. Text runs (merge contiguous visible characters of the same
            //    color; each glyph gets an explicit x so alignment does not
            //    depend on the viewer's font metrics).
            col = 0;
            while (col < row.size()) {
                const Cell& cc = row[col];
                bool line_primitive = border_segments(grid.rows, r, col).any();
                bool visible = false;
                Color color = fg_for(cc, theme, visible);
                if (!visible || cc.ch == ' ' || line_primitive) { ++col; continue; }
                std::string xs, chars;
                while (col < row.size()) {
                    bool vis2 = false;
                    Color c2 = fg_for(row[col], theme, vis2);
                    bool lp2 = border_segments(grid.rows, r, col).any();
                    if (!vis2 || row[col].ch == ' ' || lp2 || c2.r != color.r ||
                        c2.g != color.g || c2.b != color.b)
                        break;
                    if (!xs.empty()) xs += ' ';
                    xs += fmt(pad_x + col * cell_w + cell_w / 2);
                    chars += xml_escape(row[col].ch);
                    ++col;
                }
                svg += "<text x=\"" + xs + "\" y=\"" + fmt(y_off + cell_h * 0.78) +
                       "\" fill=\"" + color.to_hex() + "\">" + chars + "</text>\n";
            }
            y_off += cell_h;
        }
        y_off += gap;
    }

    svg += "</g>\n</svg>\n";
    return svg;
}

} // namespace protocol
